#!/usr/bin/env python3
"""Generate nix-config/docs/REVDEPS.md: which hosts and users load each module.

Evaluated, not parsed: reads the module system's import graph (`graph` on each
nixosConfiguration and on each home-manager user), so transitive imports through
presets, hardware flakes and default.nix aggregators all count. kleinbem-owned
inputs are indexed per file, third-party inputs per input.

Not covered: nixOnDroidConfigurations (no `graph`), flake-parts modules.
NIX_OVERRIDES (e.g. CI's dummy kleinbem-secrets) is passed to every nix call.
Regenerated by `just dev::sync-agent`.
"""

from __future__ import annotations

import json
import os
import shlex
import subprocess
import sys
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _nix_options import NIX_CONFIG, relpath

OUTPUT = NIX_CONFIG / "docs/REVDEPS.md"
OWNERS = {"kleinbem", "kleinbem-dev"}
# Every host loads these; listing them per host adds nothing.
OMIT_INPUTS = {"nixpkgs"}
# CI evaluates against a dummy tree, so its paths would churn the doc.
SKIP_INPUTS = {"kleinbem-secrets"}
# Directories whose unloaded .nix files are reported as unused.
UNUSED_SCAN = ["modules/nixos", "modules/home-manager"]
OVERRIDES = shlex.split(os.environ.get("NIX_OVERRIDES", ""))

# Flattens a module graph to the files it loaded; anonymous modules share
# their file. A disabled module's imports aren't loaded through it, so the walk
# stops there. The home-manager user graphs sit behind the submodule's valueMeta.
APPLY = r"""
c: let
  flat =
    n:
    [ { inherit (n) file disabled; } ]
    ++ (if n.disabled then [ ] else builtins.concatMap flat n.imports);
  hm = c.options.home-manager.users.valueMeta.attrs or { };
in {
  nixos = builtins.concatMap flat c.graph;
  hm = builtins.mapAttrs (_: u: builtins.concatMap flat u.configuration.graph) hm;
}
"""


def nix_json(args: list[str], timeout: int = 600):
    res = subprocess.run(
        ["nix", *args, *OVERRIDES, "--json"],
        cwd=NIX_CONFIG,
        capture_output=True,
        text=True,
        timeout=timeout,
        check=False,
    )
    if res.returncode != 0:
        lines = (res.stderr or "").strip().splitlines()
        raise RuntimeError(lines[-1] if lines else f"nix exited {res.returncode}")
    return json.loads(res.stdout)


def input_roots() -> tuple[dict[str, str], set[str]]:
    """Store path → input label ("nix-config" for self), and the owned labels."""
    tree = nix_json(["flake", "archive", "--dry-run"])
    lock = json.loads((NIX_CONFIG / "flake.lock").read_text())
    nodes = lock["nodes"]
    owned = {"nix-config"}
    for name, ref in nodes[lock["root"]]["inputs"].items():
        if (
            isinstance(ref, str)
            and nodes[ref].get("original", {}).get("owner") in OWNERS
        ):
            owned.add(name)

    roots = {tree["path"]: "nix-config"}
    # Breadth-first, so a followed input keeps its top-level name.
    queue = [("", tree["inputs"])]
    while queue:
        prefix, inputs = queue.pop(0)
        for name, sub in sorted(inputs.items()):
            label = f"{prefix}{name}"
            roots.setdefault(sub["path"], label)
            queue.append((f"{label}/", sub.get("inputs", {})))
    return roots, owned


def locate(file: str, roots: dict[str, str]) -> tuple[str, str] | None:
    """(input label, path inside it) for a store file, else None."""
    if not file.startswith("/nix/store/"):
        return None
    parts = file.split("/", 4)
    root = "/".join(parts[:4])
    if root not in roots or roots[root] in SKIP_INPUTS:
        return None
    path = parts[4] if len(parts) > 4 else ""
    # Modules declared inline in a flake output: "<file>, via option flake.x".
    if ", via option flake." in path:
        src, opt = path.split(", via option flake.", 1)
        path = f"{src}#{opt}"
    elif os.path.isdir(file):
        path = f"{path}/default.nix" if path else "default.nix"
    return roots[root], path


def eval_host(host: str):
    return nix_json(
        ["eval", "--impure", f".#nixosConfigurations.{host}", "--apply", APPLY]
    )


def main() -> int:
    try:
        hosts = nix_json(
            [
                "eval",
                "--impure",
                ".#nixosConfigurations",
                "--apply",
                "builtins.attrNames",
            ]
        )
        roots, owned = input_roots()
    except (RuntimeError, subprocess.SubprocessError, OSError) as e:
        print(f"❌ revdeps: {e}", file=sys.stderr)
        return 1

    # (label, path) → consumers; consumers are "host" or "user@host".
    files: dict[tuple[str, str], set[str]] = defaultdict(set)
    disabled: dict[tuple[str, str], set[str]] = defaultdict(set)
    failed: dict[str, str] = {}

    with ThreadPoolExecutor(max_workers=4) as pool:
        results = dict(zip(hosts, pool.map(lambda h: _safe(eval_host, h), hosts)))

    for host, res in results.items():
        if isinstance(res, Exception):
            failed[host] = str(res)
            continue
        graphs = [(host, res["nixos"])] + [
            (f"{u}@{host}", g) for u, g in sorted(res["hm"].items())
        ]
        for consumer, graph in graphs:
            for node in graph:
                loc = locate(node["file"], roots)
                if loc is None:
                    continue
                (disabled if node["disabled"] else files)[loc].add(consumer)

    # A partial index would read as "nothing else loads this"; keep the old one.
    if failed:
        for host, msg in sorted(failed.items()):
            print(f"❌ revdeps: {host}: {msg}", file=sys.stderr)
        print(
            "Some hosts failed to evaluate — refusing to overwrite REVDEPS.md",
            file=sys.stderr,
        )
        return 1
    if not files:
        print(
            "No module graphs evaluated — refusing to overwrite REVDEPS.md",
            file=sys.stderr,
        )
        return 1

    write(hosts, files, disabled, owned)
    return 0


def _safe(fn, arg):
    try:
        return fn(arg)
    except (RuntimeError, subprocess.SubprocessError, OSError) as e:
        return e


def fmt_consumers(consumers: set[str], all_hosts: set[str]) -> str:
    hosts = sorted(c for c in consumers if "@" not in c)
    users = sorted(consumers - set(hosts))
    parts = []
    if hosts:
        parts.append("all hosts" if set(hosts) == all_hosts else ", ".join(hosts))
    if users:
        parts.append("hm: " + ", ".join(users))
    return "; ".join(parts)


def write(hosts, files, disabled, owned) -> None:
    ok_hosts = set(hosts)
    by_input: dict[str, set[str]] = defaultdict(set)
    for (label, _), consumers in files.items():
        by_input[label] |= consumers

    lines = [
        "# Module Reverse Dependencies",
        "",
        "> **Auto-generated** by `nix-config/scripts/generate-revdeps-index.py`. Do not edit by hand.",
        ">",
        "> Regenerate with `just dev::sync-agent`.",
        "",
        (
            "Which hosts (and home-manager `user@host`s) load each module file, read from the "
            "evaluated module graph. Unlike `IMPORTS.md` this includes transitive imports. "
            "Grep a path to see who a change reaches. nix-on-droid hosts are not covered."
        ),
        "",
        f"**Hosts evaluated:** {len(hosts)}  ",
        f"**Files indexed:** {len({loc for loc in (*files, *disabled) if loc[0] in owned})}",
        "",
    ]
    lines += ["## Inputs → consumers", ""]
    for label in sorted(by_input):
        if label in OMIT_INPUTS:
            continue
        lines.append(f"- `{label}` ← {fmt_consumers(by_input[label], ok_hosts)}")
    lines.append("")

    for label in sorted(owned):
        paths = sorted({p for (lbl, p) in [*files, *disabled] if lbl == label})
        if not paths:
            continue
        lines += [f"## `{label}`", ""]
        for path in paths:
            loaded_by = fmt_consumers(files.get((label, path), set()), ok_hosts)
            off = disabled.get((label, path))
            mark = (
                f" _(disabledModules: {fmt_consumers(off, ok_hosts)})_" if off else ""
            )
            lines.append(f"- `{path}` ← {loaded_by or '—'}{mark}")
        lines.append("")

    loaded = {p for (lbl, p) in files if lbl == "nix-config"}
    unused = sorted(
        f.relative_to(NIX_CONFIG).as_posix()
        for d in UNUSED_SCAN
        for f in (NIX_CONFIG / d).rglob("*.nix")
        if f.relative_to(NIX_CONFIG).as_posix() not in loaded
    )
    if unused:
        lines += [
            "## Unused in nix-config",
            "",
            (
                f"Files under {', '.join(f'`{d}/`' for d in UNUSED_SCAN)} that no evaluated "
                "host or user loads: nix-on-droid or colmena-only modules, data files read with a "
                "plain `import`, or dead code."
            ),
            "",
        ]
        lines += [f"- `{p}`" for p in unused]
        lines.append("")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"✅ Wrote {relpath(OUTPUT)} ({len(ok_hosts)} hosts, {len(files)} files)")


if __name__ == "__main__":
    sys.exit(main())
